// Resolve a pathname to its help entry by trying exact match, then stripping
// trailing segments (so /students/:id → /students).
export function resolveHelp(pathname) {
  let path = pathname || '/';
  while (path && path !== '') {
    if (helpContent[path]) return helpContent[path];
    const idx = path.lastIndexOf('/');
    if (idx === 0) return null; // top-level segment with no entry
    if (idx < 0) return null;
    path = path.slice(0, idx);
  }
  return null;
}